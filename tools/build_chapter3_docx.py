from docx.oxml import OxmlElement
from docx.oxml.ns import qn

def _m(tag):
    return OxmlElement('m:' + tag)

def _mr(t):
    r = _m('r'); e = _m('t'); e.text = str(t); r.append(e)
    rpr = _m('rPr'); sty = _m('sty'); sty.set(qn('m:val'), 'p'); rpr.append(sty); r.insert(0, rpr)
    return r

def _mt(x):
    if isinstance(x, str):
        return _mr(x)
    k = x[0]
    if k == 'sub':
        o = _m('sSub'); e = _m('e'); e.append(_mt(x[1])); o.append(e)
        u = _m('sub'); u.append(_mt(x[2])); o.append(u); return o
    if k == 'sup':
        o = _m('sSup'); e = _m('e'); e.append(_mt(x[1])); o.append(e)
        u = _m('sup'); u.append(_mt(x[2])); o.append(u); return o
    return _mr('')

def eq_omml(tokens, num):
    q = doc.add_paragraph(style=EQF)
    q.alignment = WD_ALIGN_PARAGRAPH.CENTER
    q.paragraph_format.first_line_indent = Cm(0)
    om = _m('oMath')
    for t in tokens:
        om.append(_mt(t))
    q._p.append(om)
    if num:
        q.add_run('\t' + num)
    return q


